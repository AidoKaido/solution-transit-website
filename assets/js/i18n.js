(function(){
  const STORAGE_KEY = 'st_lang';
  function getLang(){ return localStorage.getItem(STORAGE_KEY) || 'fr'; }
  function setLang(l){ localStorage.setItem(STORAGE_KEY, l); }
  function applyLang(lang){
    const dict = window.I18N[lang] || window.I18N.fr;
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const v = dict[key];
      if (v == null) return;
      if (el.hasAttribute('data-i18n-html') || /<[a-z][\s\S]*>/i.test(v)) {
        el.innerHTML = v;
      } else {
        el.textContent = v;
      }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const v = dict[el.getAttribute('data-i18n-placeholder')];
      if (v != null) el.placeholder = v;
    });
    document.querySelectorAll('[data-i18n-aria]').forEach(el => {
      const v = dict[el.getAttribute('data-i18n-aria')];
      if (v != null) el.setAttribute('aria-label', v);
    });
    document.querySelectorAll('.lang-switch button').forEach(b => {
      b.classList.toggle('active', b.dataset.lang === lang);
    });
  }
  window.STLang = {
    apply: applyLang,
    get: getLang,
    set: function(l){ setLang(l); applyLang(l); }
  };
  document.addEventListener('DOMContentLoaded', () => {
    applyLang(getLang());
    document.querySelectorAll('.lang-switch button').forEach(b => {
      b.addEventListener('click', () => window.STLang.set(b.dataset.lang));
    });
  });
})();
